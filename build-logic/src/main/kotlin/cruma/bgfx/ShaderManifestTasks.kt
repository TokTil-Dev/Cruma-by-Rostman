package cruma.bgfx

import org.gradle.api.DefaultTask
import org.gradle.api.file.ConfigurableFileCollection
import org.gradle.api.file.DirectoryProperty
import org.gradle.api.file.RegularFileProperty
import org.gradle.api.provider.ListProperty
import org.gradle.api.provider.MapProperty
import org.gradle.api.tasks.Input
import org.gradle.api.tasks.InputFile
import org.gradle.api.tasks.InputFiles
import org.gradle.api.tasks.Internal
import org.gradle.api.tasks.OutputFile
import org.gradle.api.tasks.PathSensitive
import org.gradle.api.tasks.PathSensitivity
import org.gradle.api.tasks.TaskAction

private fun binaryPath(root: java.io.File, variant: String, target: String, source: String) =
    root.resolve("bgfx/shaders/$variant/$target/$source.bin")

abstract class GenerateShaderManifestTask : DefaultTask() {
    @get:InputFiles
    @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val binaries: ConfigurableFileCollection

    @get:Internal
    abstract val generatedDirectory: DirectoryProperty

    @get:Input
    abstract val pins: MapProperty<String, String>

    @get:Input
    abstract val variants: ListProperty<String>

    @get:Input
    abstract val targets: ListProperty<String>

    @get:Input
    abstract val sourceNames: ListProperty<String>

    @get:OutputFile
    abstract val manifest: RegularFileProperty

    @TaskAction
    fun generate() {
        val lines = mutableListOf("# Generated by the shader manifest task. Do not edit.")
        pins.get().forEach { (key, value) -> lines += "$key=$value" }
        lines += "targets=${targets.get().joinToString(",")}"
        val root = generatedDirectory.get().asFile
        var count = 0
        for (variant in variants.get()) {
            for (target in targets.get()) {
                for (source in sourceNames.get()) {
                    lines += "shader.$variant.$target.$source.sha256=${binaryPath(root, variant, target, source).sha256()}"
                    count++
                }
            }
        }
        lines.add(lines.indexOfFirst { it.startsWith("targets=") } + 1, "shader.count=$count")
        val output = manifest.get().asFile
        output.parentFile.mkdirs()
        output.writeText(lines.joinToString(System.lineSeparator()) + System.lineSeparator())
    }
}

abstract class ValidateShaderManifestTask : DefaultTask() {
    @get:InputFiles
    @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val shaderSources: ConfigurableFileCollection

    @get:InputFiles
    @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val binaries: ConfigurableFileCollection

    @get:InputFile
    @get:PathSensitive(PathSensitivity.NONE)
    abstract val manifest: RegularFileProperty

    @get:Internal
    abstract val generatedDirectory: DirectoryProperty

    @get:Input
    abstract val variants: ListProperty<String>

    @get:Input
    abstract val targets: ListProperty<String>

    @get:Input
    abstract val sourceNames: ListProperty<String>

    @get:OutputFile
    abstract val report: RegularFileProperty

    @TaskAction
    fun validate() {
        val entityVariants = shaderSources.files.count { Regex("fs_scene_(entity|ordinary|csg|water)\\.sc").matches(it.name) }
        if (entityVariants > 48) {
            throw IllegalStateException("Entity shader manifest has $entityVariants linked variants; explicit review is required above 48")
        }
        val samplerPattern = Regex("(?m)^\\s*SAMPLER(?:2D|3D|CUBE|2DSHADOW)\\s*\\(")
        for (source in shaderSources.files.filter { it.isFile }) {
            val samplers = samplerPattern.findAll(source.readText()).count()
            if (samplers > 16) {
                throw IllegalStateException("${source.name} declares $samplers samplers; portable bgfx limit is 16")
            }
        }
        val root = generatedDirectory.get().asFile
        var checked = 0
        for (variant in variants.get()) {
            for (target in targets.get()) {
                for (source in sourceNames.get()) {
                    val binary = binaryPath(root, variant, target, source)
                    if (!binary.isFile || binary.length() == 0L) {
                        throw IllegalStateException("Missing bgfx shader binary: $binary")
                    }
                    checked++
                }
            }
        }
        if (!manifest.get().asFile.isFile) {
            throw IllegalStateException("Missing shader manifest ${manifest.get().asFile}")
        }
        report.get().asFile.writeText("binaries=$checked\n")
    }
}
