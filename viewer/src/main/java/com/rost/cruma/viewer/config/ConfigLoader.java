    public record Options(
            Path configDirectory,
            boolean printConfig,
            boolean printConfigDir,
            Path client,
            boolean noClientPicker,
            @Nullable String map,
            boolean effects,
            boolean editing,
            @Nullable String scene,
            @Nullable Path sceneFile,
            @Nullable RecordOptions record,
            boolean agent,
            boolean hidden,
            boolean headless,
            @Nullable List<String> tiles,
            @Nullable String camera) {
        public Options(Path configDirectory, boolean printConfig, boolean printConfigDir) {
            this(configDirectory, printConfig, printConfigDir, null, false);
        }

        public Options(
                Path configDirectory,
                boolean printConfig,
                boolean printConfigDir,
                Path client,
                boolean noClientPicker) {
            this(configDirectory, printConfig, printConfigDir, client, noClientPicker, null);
        }

        public Options(
                Path configDirectory,
                boolean printConfig,
                boolean printConfigDir,
                Path client,
                boolean noClientPicker,
                @Nullable String map) {
            this(
                    configDirectory,
                    printConfig,
                    printConfigDir,
                    client,
                    noClientPicker,
                    map,
                    false,
                    false,
                    null,
                    null,
                    null,
                    false,
                    false,
                    false,
                    null,
                    null);
        }
    }

    public static String usage() {
        return """
            Usage: cruma [command] [options]

            No arguments: open the start menu.
            Configuration is stored automatically in the OS user configuration directory.

            Commands:
              viewer      open the start menu (optional. Same as no command)
              capture     render every configured map tile to an image
              mcp         serve an AI agent on standard input and output
              tables      say how Cruma reads the tables of a client, with no window (cruma tables --help)
              help        show this text

            Options:
              -c, --config <dir>   configuration directory (default: the OS user configuration directory)
                  --print-config   print the effective configuration (defaults + overrides) and exit
                  --config-dir     print the resolved configuration directory and exit
                  --client <dir>   use this client without opening the client picker
                  --no-client-picker  use the configured client without opening the picker
                  --map <name>     open a map of the client that is not a world tile, such as Lobby01, in place of the world
                  --effects        open the Effects tool with no map, to look at the client's effects and skills
                  --editing        open the Viewer in Edit, with its tiles loaded for it at once
                  --scene <name>   open the tiles of a cut scene of the game, such as sc_boss_freya_opening, and play it
                  --scene-file <file>  open the tiles of a scene of the video director, a .scene.json file, and play it
                  --record <file>  with --scene or --scene-file: write the scene as an MP4 file, with no window, and exit. It needs ffmpeg
                  --record-size <width>x<height>  the size of the video, even numbers, such as 1920x1080
                  --record-rate <n>  the frames a second of the video, such as 60
                  --record-from <seconds>  start the video this far into the scene
                  --record-to <seconds>  end the video this far into the scene
                  --record-hour <hour>  the hour of the game day in the video, from 0 to 24, such as 18.5. It goes before the hour of a scene file
                  --tiles <list>   open only these tiles, such as 22_22,23_22
                  --camera <x,y,z,yaw,pitch>  where the camera starts
                  --hidden         open the viewer with no window
                  --headless       open the viewer with no display and no graphics card, so it draws no pictures
                  --agent          let the agent that started this viewer use it\
            """;
    }

    public static Options parseOptions(String[] args) {
        Path directory = null;
        var printConfig = false;
        var printConfigDir = false;
        Path client = null;
        boolean noClientPicker = false;
        String map = null;
        var effects = false;
        var editing = false;
        String scene = null;
        Path sceneFile = null;
        var agent = false;
        var hidden = false;
        var headless = false;
        List<String> tiles = null;
        String camera = null;
        var record = new Parser();
        for (var i = 0; i < args.length; i++) {
            var arg = args[i];
            switch (arg) {
                case "-c", "--config" -> {
                    if (i + 1 >= args.length) {
                        throw new ConfigurationProblem(arg + " needs a directory argument");
                    }
                    directory = Paths.get(args[++i]);
                }
                case "--client" -> {
                    if (i + 1 >= args.length || args[i + 1].isBlank()) {
                        throw new ConfigurationProblem("--client needs a game folder argument");
                    }
                    client = Paths.get(args[++i]);
                }
                case "--map" -> {
                    if (i + 1 >= args.length || args[i + 1].isBlank()) {
                        throw new ConfigurationProblem("--map needs a map name, such as Lobby01");
                    }
                    map = args[++i];
                }
                case "--scene" -> {
                    if (i + 1 >= args.length || args[i + 1].isBlank()) {
                        throw new ConfigurationProblem(
                                "--scene needs the name of a cut scene, such as sc_boss_freya_opening");
                    }
                    scene = args[++i];
                }
                case "--scene-file" -> {
                    if (i + 1 >= args.length || args[i + 1].isBlank()) {
                        throw new ConfigurationProblem("--scene-file needs a .scene.json file of the video director");
                    }
                    sceneFile = Paths.get(args[++i]);
                }
                case "--tiles" -> {
                    if (i + 1 >= args.length || args[i + 1].isBlank()) {
                        throw new ConfigurationProblem("--tiles needs a list of tiles, such as 22_22,23_22");
                    }
                    tiles = List.of(args[++i].split(","));
                }
                case "--camera" -> {
                    if (i + 1 >= args.length || args[i + 1].split(",").length != 5) {
                        throw new ConfigurationProblem("--camera needs x,y,z,yaw,pitch");
                    }
                    camera = args[++i];
                }
                case "--agent" -> agent = true;
                case "--hidden" -> hidden = true;
                case "--headless" -> headless = true;
                case "--no-client-picker" -> noClientPicker = true;
                case "--effects" -> effects = true;
                case "--editing" -> editing = true;
                case "--print-config" -> printConfig = true;
                case "--config-dir" -> printConfigDir = true;
                default -> {
                    if (arg.startsWith("--config=")) {
                        directory = Paths.get(arg.substring("--config=".length()));
                    } else if (record.takes(arg)) {
                        i += record.read(args, i);
                    } else {
                        throw new ConfigurationProblem("Unknown option '" + arg + "'.\n" + usage());
                    }
                }
            }
        }
        if (scene != null && sceneFile != null) {
            throw new ConfigurationProblem("--scene and --scene-file each name a scene: use one of them");
        }
        return new Options(
                directory,
                printConfig,
                printConfigDir,
                client,
                noClientPicker,
                map,
                effects,
                editing,
                scene,
                sceneFile,
                record.build(scene != null || sceneFile != null),
                agent,
                hidden || headless,
                headless,
                tiles,
                camera);
    }

    static Path defaultDirectory(String osName, Map<String, String> env, String home) {
        var os = osName.toLowerCase(Locale.ROOT);
        if (os.contains("mac")) {
            return Paths.get(home, "Library", "Application Support", "Cruma");
        }
        if (os.contains("win")) {
            var appData = env.get("APPDATA");
            return appData == null || appData.isBlank()
                    ? Paths.get(home, "AppData", "Roaming", "Cruma")
                    : Paths.get(appData, "Cruma");
        }
        var xdg = env.get("XDG_CONFIG_HOME");
        return xdg == null || xdg.isBlank() ? Paths.get(home, ".config", "cruma") : Paths.get(xdg, "cruma");
    }

    public static Config builtInDefaults() {
        return Config.parseConfig(
                ConfigFactory.parseString(readDefaultsResource()).resolve());
    }

    public static void requireClientPath(Path clientPath, String key, Path userFile) {
        if (clientPath == null || clientPath.toString().isBlank()) {
            throw new ConfigurationProblem(
                    key + " is not set. Edit " + userFile + " and point it at an installed Lineage II client.");
        }
        if (!Files.isDirectory(clientPath)) {
            throw new ConfigurationProblem(
                    key + " = " + clientPath + " is not a directory (configured in " + userFile + ")");
        }
    }

    public Options getOptions() {
        return options;
    }

    public Path getConfigDirectory() {
        if (options.configDirectory() != null) {
            return options.configDirectory().toAbsolutePath().normalize();
        }
        return defaultDirectory(System.getProperty("os.name"), System.getenv(), System.getProperty("user.home"));
    }

    public Config load() {
        var merged = mergedConfig();
        try {
            return Config.parseConfig(merged, getConfigDirectory());
        } catch (IllegalArgumentException | ConfigException failure) {
            throw new ConfigurationProblem(
                    "Invalid setting in " + getConfigDirectory().resolve(USER_FILE) + ": " + failure.getMessage(),
                    failure);
        }
    }

    public String renderEffectiveConfig() {
        var options = ConfigRenderOptions.defaults()
                .setOriginComments(false)
                .setJson(false)
                .setFormatted(true)
                .setComments(true);
        return mergedConfig().root().render(options);
    }

    public com.typesafe.config.Config getEffectiveSettings() {
        return mergedConfig();
    }

    public com.typesafe.config.Config readSettings() {
        var userFile = getConfigDirectory().resolve(USER_FILE);
        if (!Files.isRegularFile(userFile)) {
            return loadSettingsFrom(ConfigFactory.empty());
        }
        try {
            return loadSettingsFrom(ConfigFactory.parseFile(userFile.toFile()));
        } catch (ConfigException e) {
            throw new ConfigurationProblem("Cannot parse " + userFile + ": " + e.getMessage(), e);
        }
    }

    public void reload() {
        merged = null;
    }

    com.typesafe.config.Config loadSettingsFrom(String text) {
        return loadSettingsFrom(loadUserSettingsFrom(text));
    }

    com.typesafe.config.Config loadSettingsFrom(com.typesafe.config.Config user) {
        var directory = getConfigDirectory();
        var userFile = directory.resolve(USER_FILE);
        return resolveSettings(user, ConfigFactory.parseString(readDefaultsResource()), directory, userFile);
    }

    com.typesafe.config.Config loadUserSettingsFrom(String text) {
        var directory = getConfigDirectory();
        var userFile = directory.resolve(USER_FILE);
        try {
            var options = ConfigParseOptions.defaults()
                    .setOriginDescription(userFile.toString())
                    .setIncluder(new SnapshotIncluder(directory, null));
            return ConfigFactory.parseString(text, options);
        } catch (ConfigException e) {
            throw new ConfigurationProblem("Cannot parse " + userFile + ": " + e.getMessage(), e);
        }
    }

    private record SnapshotIncluder(Path directory, ConfigIncluder fallback) implements ConfigIncluder {
        @Override
        public ConfigIncluder withFallback(ConfigIncluder includer) {
            if (fallback == includer || this == includer) {
                return this;
            }
            return new SnapshotIncluder(directory, fallback == null ? includer : fallback.withFallback(includer));
        }

        @Override
        public ConfigObject include(ConfigIncludeContext context, String name) {
            return fallback.include(new SnapshotIncludeContext(directory, context), name);
        }
    }

    private record SnapshotIncludeContext(Path directory, ConfigIncludeContext context)
            implements ConfigIncludeContext {
        @Override
        public ConfigParseable relativeTo(String name) {
            return new SnapshotInclude(directory.resolve(name), parseOptions().setSyntaxFromFilename(name));
        }

        @Override
        public ConfigParseOptions parseOptions() {
            return context.parseOptions().setIncluder(null);
        }

        @Override
        public ConfigIncludeContext setParseOptions(ConfigParseOptions options) {
            return new SnapshotIncludeContext(directory, context.setParseOptions(options));
        }
    }

    private record SnapshotInclude(Path file, ConfigParseOptions options) implements ConfigParseable {
        @Override
        public ConfigObject parse(ConfigParseOptions options) {
            return ConfigFactory.parseFile(file.toFile(), options).root();
        }

        @Override
        public ConfigOrigin origin() {
            return ConfigFactory.empty(file.toString()).root().origin();
        }
    }

