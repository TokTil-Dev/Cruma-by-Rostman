    public Config forClient(Path client, String tile, boolean capture) {
        return forClient(client, tile, capture, null);
    }

    public Config forClient(Path client, String tile, boolean capture, @Nullable String place) {
        var prefix = capture ? "capture" : "viewer";
        var config = mergedConfig()
                .withValue(prefix + ".world.client_path", ConfigValueFactory.fromAnyRef(client.toString()));
        config = capture
                ? ClientProfiles.applyVariant(config, client, getConfigDirectory())
                : ClientProfiles.apply(config, client, getConfigDirectory());
        if (!tile.isEmpty()) {
            var all = ClientInstallation.ALL_TILES.equals(tile);
            if (!all && !TileSelection.isExplicit(tile)) {
                throw new ConfigurationProblem("Select at least one valid world tile.");
            }
            var variant = WorldVariant.parse(config.getString(prefix + ".world.variant"));
            var tiles = all ? ClientInstallation.inspect(client, variant).tiles() : TileSelection.parse(tile);
            var x = tiles.stream()
                    .mapToInt(value -> Integer.parseInt(value.split("_")[0]))
                    .summaryStatistics();
            var y = tiles.stream()
                    .mapToInt(value -> Integer.parseInt(value.split("_")[1]))
                    .summaryStatistics();
            var bounds = Map.of(
                    "min_x_tile",
                    x.getMin(),
                    "max_x_tile",
                    x.getMax(),
                    "min_y_tile",
                    y.getMin(),
                    "max_y_tile",
                    y.getMax());
            for (var entry : bounds.entrySet()) {
                config = config.withValue(
                        prefix + ".world." + entry.getKey(), ConfigValueFactory.fromAnyRef(entry.getValue()));
            }
            if (!capture) {
                var camera = load().viewer().camera();
                var start = StartCamera.choose(tiles, camera.start(), new StartPlaces(camera.locations()), place);
                if (start != null) {
                    config = config.withValue("viewer.camera.start", ConfigValueFactory.fromAnyRef(start.toSetting()));
                    if (start.fallback()) {
                        config = config.withValue("viewer.camera.start_pitch", ConfigValueFactory.fromAnyRef(-35));
                    }
                }
            }
        }
        return Config.parseConfig(config, getConfigDirectory());
    }

    public Config forMapPreview(ClientInstallation installation, Path directory) {
        var cache = new MapPreviewCache(getConfigDirectory(), installation);
        var x = installation.tiles().stream()
                .mapToInt(tile -> Integer.parseInt(tile.split("_")[0]))
                .summaryStatistics();
        var y = installation.tiles().stream()
                .mapToInt(tile -> Integer.parseInt(tile.split("_")[1]))
                .summaryStatistics();
        var preset = ConfigFactory.parseResources(DEFAULTS_RESOURCE)
                .withValue(
                        "viewer.world.client_path",
                        ConfigValueFactory.fromAnyRef(installation.root().toString()));
        var values = Map.<String, Object>ofEntries(
                Map.entry("capture.world.min_x_tile", x.getMin()),
                Map.entry("capture.world.max_x_tile", x.getMax()),
                Map.entry("capture.world.min_y_tile", y.getMin()),
                Map.entry("capture.world.max_y_tile", y.getMax()),
                Map.entry("capture.world.variant", installation.variant().getKey()),
                Map.entry("capture.world.rendering.texture_detail", 2),
                Map.entry("capture.world.rendering.effect_texture_detail", 2),
                Map.entry("capture.world.rendering.bloom_enabled", false),
                Map.entry("capture.output.directory", directory.toString()),
                Map.entry("capture.output.tile_resolution", MapPreviewCache.CAPTURE_RESOLUTION),
                Map.entry("capture.output.write_tiles", false),
                Map.entry("capture.output.client_subfolder", false),
                Map.entry("capture.output.delete_old_images", false),
                Map.entry("capture.output.open_folder_on_complete", false),
                Map.entry("capture.output.radar.enabled", true),
                Map.entry("capture.output.radar.file", "capture.png"),
                Map.entry("capture.output.radar.tile_resolution", cache.getTileResolution()),
                Map.entry(
                        "capture.output.views",
                        preset.getConfigList("capture.output.views").stream()
                                .filter(view -> view.hasPath("main") && view.getBoolean("main"))
                                .map(com.typesafe.config.Config::root)
                                .toList()));
        for (var entry : values.entrySet()) {
            preset = preset.withValue(entry.getKey(), ConfigValueFactory.fromAnyRef(entry.getValue()));
        }
        preset = preset.withValue(ClientProfiles.LIST, mergedConfig().getValue(ClientProfiles.LIST));
        return Config.parseConfig(preset.resolve(), getConfigDirectory());
    }

    private com.typesafe.config.Config mergedConfig() {
        if (merged != null) {
            return merged;
        }
        var defaultsText = readDefaultsResource();
        var defaults = ConfigFactory.parseString(defaultsText);
        var directory = getConfigDirectory();
        var userFile = directory.resolve(USER_FILE);
        try {
            Files.createDirectories(directory);
            Files.writeString(directory.resolve(DEFAULTS_COPY), DEFAULTS_COPY_HEADER + defaultsText);
            if (!Files.exists(userFile)) {
                Files.writeString(userFile, TEMPLATE);
            }
        } catch (IOException e) {
            throw new UncheckedIOException("Cannot prepare the configuration directory " + directory, e);
        }
        com.typesafe.config.Config user;
        try {
            user = ConfigFactory.parseFile(userFile.toFile());
        } catch (ConfigException e) {
            throw new ConfigurationProblem("Cannot parse " + userFile + ": " + e.getMessage(), e);
        }
        merged = resolveSettings(user, defaults, directory, userFile);
        return merged;
    }

    private com.typesafe.config.Config resolveSettings(
            com.typesafe.config.Config user, com.typesafe.config.Config defaults, Path directory, Path userFile) {
        var problems = new ConfigValidator(defaults).findProblems(user);
        if (!problems.isEmpty()) {
            throw new ConfigurationProblem("Invalid keys in "
                    + userFile
                    + ":\n  "
                    + String.join("\n  ", problems)
                    + "\nSee "
                    + directory.resolve(DEFAULTS_COPY)
                    + " for every supported key.");
        }
        try {
            var configured = ConfigMigrations.mergeWithDefaults(user, defaults);
            var resolved = ClientProfiles.migrateLegacy(configured, directory);
            if (options.client() != null) {
                user = user.withValue(
                        "viewer.world.client_path",
                        ConfigValueFactory.fromAnyRef(
                                options.client().toAbsolutePath().normalize().toString()));
                user = user.withValue(
                        "capture.world.client_path",
                        ConfigValueFactory.fromAnyRef(
                                options.client().toAbsolutePath().normalize().toString()));
                var migratedProfiles = resolved.getObject(ClientProfiles.LIST);
                for (var key : configured.getObject(ClientProfiles.LIST).keySet()) {
                    migratedProfiles = migratedProfiles.withoutKey(key);
                }
                resolved = ConfigMigrations.mergeWithDefaults(user, defaults);
                resolved = resolved.withValue(
                        ClientProfiles.LIST,
                        resolved.getObject(ClientProfiles.LIST).withFallback(migratedProfiles));
            }
            resolved = ClientProfiles.bindVariant(resolved, directory);
            if (options.headless()) {
                resolved = resolved.withValue(
                        "viewer.world.rendering.graphics.renderer", ConfigValueFactory.fromAnyRef("noop"));
            }
            return ClientProfiles.apply(resolved, Path.of(resolved.getString("viewer.world.client_path")), directory);
        } catch (ConfigException | IllegalArgumentException e) {
            throw new ConfigurationProblem("Cannot resolve " + userFile + ": " + e.getMessage(), e);
        }
    }

    private static String readDefaultsResource() {
        try (InputStream stream = ConfigLoader.class.getClassLoader().getResourceAsStream(DEFAULTS_RESOURCE)) {
            if (stream == null) {
                throw new IllegalStateException("Built-in defaults " + DEFAULTS_RESOURCE + " are missing from the jar");
            }
            return new String(stream.readAllBytes(), StandardCharsets.UTF_8);
        } catch (IOException e) {
            throw new UncheckedIOException("Cannot read built-in defaults", e);
        }
    }
